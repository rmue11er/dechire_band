/**
 * A small, curated slice of Font Awesome Free (Solid) – only the icons a band
 * document realistically needs. Keeping the list short matters: every icon is a
 * path string that ends up in the client bundle and in the document HTML.
 *
 * Licence: Font Awesome Free – Icons CC BY 4.0, Fonts SIL OFL 1.1, Code MIT.
 * https://fontawesome.com/license/free
 */
export type DocIconDef = {
  name: string;
  label: string;
  group: string;
  viewBox: string;
  paths: string[];
};

const registry = new Map<string, DocIconDef>();

const pack = (group: string, entries: Record<string, IconDefinition>) => {
  Object.entries(entries).forEach(([name, definition]) => {
    const [width, height, , , data] = definition.icon;
    registry.set(name, {
      name,
      group,
      label: definition.iconName.replace(/-/g, ' '),
      viewBox: `0 0 ${width} ${height}`,
      paths: Array.isArray(data) ? data : [data],
    });
  });
};

