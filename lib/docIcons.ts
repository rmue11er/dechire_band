export const DOC_ICON_GROUPS = ['Band', 'Mood', 'On the road', 'Orga', 'Promo', 'Marks'].map(
  (name) => ({
    name,
    items: DOC_ICONS.filter((icon) => icon.group === name),
  }),
);

const FALLBACK: DocIconDef = {
  name: 'star',
  label: 'star',
  group: 'Marks',
  viewBox: '0 0 576 512',
  paths: [],
};

export function iconDef(name: string): DocIconDef {
  return registry.get(name) ?? registry.get('star') ?? FALLBACK;
}
